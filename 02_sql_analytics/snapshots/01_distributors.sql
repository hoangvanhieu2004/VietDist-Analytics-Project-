-- snapshots.distributors — lưu lịch sử SCD2 của nhà phân phối (giống dbt snapshot). Task 3.1
-- Nguồn chỉ có snapshot hiện tại (không có lịch sử) -> lịch sử tích luỹ qua các lần chạy (A-32),
-- nên đây là BẢNG cập nhật tăng dần (merge), KHÔNG build lại. dwh.dim_distributors là view trên bảng này.
-- Thuộc tính theo dõi lịch sử: tier, region, channel (BR-B-02). Thuộc tính khác: ghi đè (SCD1).
-- Mỗi lần chạy, so stg_distributors với bản ghi hiện hành:
--   1. tier/region/channel đổi -> đóng bản ghi cũ (effective_to = load_date − 1), thêm bản ghi mới
--      hiệu lực từ load_date (= ngày load snapshot vào Bronze). Nếu đổi trong cùng ngày bản ghi
--      hiện hành bắt đầu -> ghi đè tại chỗ (không tạo khoảng hiệu lực âm).
--   2. NPP mới -> thêm bản ghi, effective_from = join_date.
--   3. Thuộc tính SCD1 (tên, liên hệ, status, credit_limit, supervisor...) -> ghi đè trên bản ghi hiện hành.
-- Chạy lại không có thay đổi -> không làm gì (idempotent). distributor_sk ổn định giữa các lần chạy.
-- =====================================================================================
CREATE SCHEMA IF NOT EXISTS snapshots;

CREATE TABLE IF NOT EXISTS snapshots.distributors (
    distributor_sk          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distributor_id          text        NOT NULL,
    distributor_name        text,
    tier                    text,
    channel                 text,
    region                  text,
    province                text,
    contact_person          text,
    phone                   text,
    email                   text,
    tax_code                text,
    join_date               date,
    credit_limit            numeric,
    status                  text,
    assigned_supervisor_id  text,
    effective_from          date        NOT NULL,
    effective_to            date        NOT NULL,
    is_current              boolean     NOT NULL,
    change_reason           text,
    _updated_at             timestamp   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_snap_distributors_current ON snapshots.distributors (distributor_id) WHERE is_current;
CREATE INDEX IF NOT EXISTS ix_snap_distributors_lookup ON snapshots.distributors (distributor_id, effective_from, effective_to);

-- Snapshot cần merge + ngày load
DROP TABLE IF EXISTS src_distributors;
CREATE TEMP TABLE src_distributors ON COMMIT DROP AS
SELECT s.*, s._ingested_at::date AS load_date
FROM staging.stg_distributors s;

-- 1a. Đổi tier/region/channel trong cùng ngày bản ghi hiện hành bắt đầu -> ghi đè tại chỗ
UPDATE snapshots.distributors d
SET tier = s.tier, region = s.region, channel = s.channel, _updated_at = now()
FROM src_distributors s
WHERE d.distributor_id = s.distributor_id AND d.is_current
  AND (d.tier, d.region, d.channel) IS DISTINCT FROM (s.tier, s.region, s.channel)
  AND s.load_date <= d.effective_from;

-- 1b. Đổi tier/region/channel -> đóng bản ghi hiện hành
UPDATE snapshots.distributors d
SET effective_to = s.load_date - 1, is_current = false, _updated_at = now()
FROM src_distributors s
WHERE d.distributor_id = s.distributor_id AND d.is_current
  AND (d.tier, d.region, d.channel) IS DISTINCT FROM (s.tier, s.region, s.channel)
  AND s.load_date > d.effective_from;

-- 2. Thêm bản ghi hiện hành cho NPP mới và NPP vừa được đóng ở bước 1b
INSERT INTO snapshots.distributors (distributor_id, distributor_name, tier, channel, region, province,
                                    contact_person, phone, email, tax_code, join_date, credit_limit, status,
                                    assigned_supervisor_id, effective_from, effective_to, is_current, change_reason)
SELECT s.distributor_id, s.distributor_name, s.tier, s.channel, s.region, s.province,
       s.contact_person, s.phone, s.email, s.tax_code, s.join_date, s.credit_limit, s.status,
       s.assigned_supervisor_id,
       CASE WHEN h.distributor_id IS NULL THEN coalesce(s.join_date, s.load_date) ELSE s.load_date END,
       DATE '9999-12-31',
       true,
       CASE WHEN h.distributor_id IS NULL THEN 'Khởi tạo' ELSE 'Thay đổi tier/region/channel' END
FROM src_distributors s
LEFT JOIN (SELECT DISTINCT distributor_id FROM snapshots.distributors) h USING (distributor_id)
WHERE NOT EXISTS (SELECT 1 FROM snapshots.distributors d
                  WHERE d.distributor_id = s.distributor_id AND d.is_current);

-- 3. Thuộc tính SCD1: ghi đè trên bản ghi hiện hành
UPDATE snapshots.distributors d
SET distributor_name = s.distributor_name, province = s.province, contact_person = s.contact_person,
    phone = s.phone, email = s.email, tax_code = s.tax_code, join_date = s.join_date,
    credit_limit = s.credit_limit, status = s.status, assigned_supervisor_id = s.assigned_supervisor_id,
    _updated_at = now()
FROM src_distributors s
WHERE d.distributor_id = s.distributor_id AND d.is_current
  AND (d.distributor_name, d.province, d.contact_person, d.phone, d.email, d.tax_code, d.join_date,
       d.credit_limit, d.status, d.assigned_supervisor_id)
      IS DISTINCT FROM
      (s.distributor_name, s.province, s.contact_person, s.phone, s.email, s.tax_code, s.join_date,
       s.credit_limit, s.status, s.assigned_supervisor_id);
